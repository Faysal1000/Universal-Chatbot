"""Generate Pydantic v2 models from the shared JSON Schemas in ``services/rag/contracts``.

The contracts are the single source of truth; the generated modules are committed so the
runtime image does not need the generator. ``--check`` regenerates into a temporary
directory and fails when the committed files are stale (run in CI and by the test suite).

Usage:
    python scripts/generate_contract_models.py            # (re)generate
    python scripts/generate_contract_models.py --check    # verify the committed files
"""

import argparse
import filecmp
import subprocess
import sys
import tempfile
from pathlib import Path

SERVICE_DIRECTORY = Path(__file__).resolve().parent.parent
DEFAULT_CONTRACTS_DIRECTORY = SERVICE_DIRECTORY.parent / "rag" / "contracts"
GENERATED_PACKAGE_DIRECTORY = SERVICE_DIRECTORY / "app" / "contracts" / "generated"
SCHEMA_FILE_SUFFIX = ".schema.json"
PACKAGE_INIT_CONTENT = '"""Generated by scripts/generate_contract_models.py. Do not edit."""\n'
GENERATOR_OPTIONS = (
    "--input-file-type=jsonschema",
    "--output-model-type=pydantic_v2.BaseModel",
    "--target-python-version=3.12",
    "--formatters=builtin",
    "--use-annotated",
    "--use-standard-collections",
    "--use-union-operator",
    "--use-title-as-name",
    "--enum-field-as-literal=all",
    "--field-constraints",
    "--use-schema-description",
    "--use-field-description",
    "--use-double-quotes",
    "--disable-timestamp",
)


def module_name_for_schema(schema_path: Path) -> str:
    """``parse-pages.v1.schema.json`` -> ``parse_pages_v1``."""
    stem = schema_path.name.removesuffix(SCHEMA_FILE_SUFFIX)
    return stem.replace("-", "_").replace(".", "_")


def find_schema_files(contracts_directory: Path) -> list[Path]:
    return sorted(contracts_directory.glob(f"*{SCHEMA_FILE_SUFFIX}"))


def generate_module(schema_path: Path, output_path: Path) -> None:
    command = [
        sys.executable,
        "-m",
        "datamodel_code_generator",
        f"--input={schema_path}",
        f"--output={output_path}",
        *GENERATOR_OPTIONS,
    ]
    subprocess.run(command, check=True, cwd=schema_path.parent)  # noqa: S603 - fixed argv, no shell.


def generate_package(contracts_directory: Path, output_directory: Path) -> None:
    output_directory.mkdir(parents=True, exist_ok=True)
    (output_directory / "__init__.py").write_text(PACKAGE_INIT_CONTENT, encoding="utf-8")
    for schema_path in find_schema_files(contracts_directory):
        generate_module(schema_path, output_directory / f"{module_name_for_schema(schema_path)}.py")


def list_stale_files(expected_directory: Path, committed_directory: Path) -> list[str]:
    expected_names = sorted(path.name for path in expected_directory.glob("*.py"))
    committed_names = sorted(path.name for path in committed_directory.glob("*.py"))
    if expected_names != committed_names:
        return sorted(set(expected_names) ^ set(committed_names))
    _, mismatched, errors = filecmp.cmpfiles(
        expected_directory, committed_directory, expected_names, shallow=False
    )
    return mismatched + errors


def main() -> int:
    argument_parser = argparse.ArgumentParser(description=__doc__)
    argument_parser.add_argument("--check", action="store_true", help="fail if committed models are stale")
    argument_parser.add_argument("--contracts", type=Path, default=DEFAULT_CONTRACTS_DIRECTORY)
    arguments = argument_parser.parse_args()

    if not arguments.check:
        generate_package(arguments.contracts, GENERATED_PACKAGE_DIRECTORY)
        print(f"Generated contract models in {GENERATED_PACKAGE_DIRECTORY}")
        return 0
    with tempfile.TemporaryDirectory() as temporary_directory:
        expected_directory = Path(temporary_directory)
        generate_package(arguments.contracts, expected_directory)
        stale_files = list_stale_files(expected_directory, GENERATED_PACKAGE_DIRECTORY)
    if stale_files:
        print(f"Generated contract models are stale: {', '.join(stale_files)}. Re-run the generator.")
        return 1
    print("Generated contract models are up to date.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
